/**
 * Shared compendium pack configuration — the single source of truth for the
 * pack build (build-packs.mjs) and the validator (validate.mjs), so the two
 * can never drift on pack names, id derivation, or source layout.
 *
 * Source layout: one JSON file per document under packs/_source/<file>/, each
 * with a human-friendly `key` slug (no ids). Ids are derived deterministically
 * from (pack, key), so rebuilding never reshuffles them.
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SRC = join(ROOT, "packs", "_source");
export const OUT = join(ROOT, "packs");

/**
 * file → output pack, document class & subtype. Must match system.json packs[]
 * (and an Item/Actor subtype must be declared in system.json documentTypes).
 * The sources are GENERATED by tools/pack-content.mjs (run by `npm run build:packs`).
 * `subtype: null` on an Actor pack means each document names its own `type`.
 */
export const PACKS = [
  { file: "houses", out: "houses", collection: "journal", type: "JournalEntry", subtype: null, label: "Houses" },
  { file: "gang", out: "gang", collection: "actors", type: "Actor", subtype: "cat", label: "Meet the Gang" },
  { file: "residents", out: "residents", collection: "actors", type: "Actor", subtype: null, label: "Residents" },
  { file: "scenes", out: "ready-to-play", collection: "scenes", type: "Scene", subtype: null, label: "Ready to Play" }
];

/** Deterministic 16-char alphanumeric id from a namespace + key (sha256 hex prefix). */
export function makeId(...parts) {
  return createHash("sha256").update(parts.join("::")).digest("hex").slice(0, 16);
}

/**
 * Read a pack's source: one JSON file per document under packs/_source/<name>/,
 * returned as an array sorted by filename (deterministic for reproducible builds).
 */
export function readSource(file) {
  const dir = join(SRC, file);
  if (!existsSync(dir)) throw new Error(`pack source folder missing: packs/_source/${file}/`);
  return readdirSync(dir)
    .filter(f => f.endsWith(".json"))
    .sort()
    .map(f => JSON.parse(readFileSync(join(dir, f), "utf8")));
}

const manifest = JSON.parse(readFileSync(join(ROOT, "system.json"), "utf8"));

/** Provenance stamped on every document. */
export const STATS = {
  // Oldest core whose schema this data fits: v13 refuses to import documents
  // stamped with a newer core, and v14 migrates up from here.
  coreVersion: "13.351",
  systemId: manifest.id,
  systemVersion: manifest.version,
  createdTime: null,
  modifiedTime: null,
  lastModifiedBy: null,
  compendiumSource: null,
  duplicateSource: null,
  exportSource: null
};

/**
 * Turn one of our source docs into a CLI-ready document (deterministic `_id`,
 * `_key`, `_stats`, inline embedded pages). Shared by the build and validator.
 */
export function toCliDoc(def, raw, index) {
  const id = makeId(def.out, raw.key);
  const sort = (index + 1) * 100;

  if (def.type === "JournalEntry") {
    return {
      _id: id,
      _key: `!journal!${id}`,
      name: raw.name,
      pages: (raw.pages ?? []).map((page, p) => {
        const pid = makeId(def.out, raw.key, page.key ?? String(p));
        return {
          _id: pid,
          _key: `!journal.pages!${id}.${pid}`,
          name: page.name,
          type: page.type ?? "text",
          title: page.title ?? { show: true, level: 1 },
          text: page.text ?? { format: 1, content: "" },
          sort: (p + 1) * 100,
          ownership: { default: -1 },
          flags: {},
          _stats: STATS
        };
      }),
      categories: [],
      folder: null,
      sort,
      ownership: { default: 0 },
      flags: raw.flags ?? {},
      _stats: STATS
    };
  }

  if (def.type === "Scene") {
    // A ready-to-play scene (tools/pack-content.mjs sceneDocs): the house's tabletop plan as the
    // background, the grid, the first view, the house journal, and the layout flags the token
    // placement reads. No tokens: the quick start puts the world's own actors on it.
    return {
      _id: id,
      _key: `!scenes!${id}`,
      name: raw.name,
      active: false,
      navigation: false,
      background: { src: raw.background },
      thumb: raw.thumb ?? null,
      width: raw.width,
      height: raw.height,
      padding: 0,
      initial: raw.initial ?? null,
      backgroundColor: raw.backgroundColor ?? "#f7f0e1",
      grid: raw.grid,
      tokenVision: false,
      fog: { exploration: false },
      environment: { darknessLevel: 0 },
      journal: raw.journal ?? null,
      drawings: [], tokens: [], levels: [], lights: [], notes: [], regions: [], sounds: [], templates: [], tiles: [], walls: [],
      folder: null,
      sort,
      ownership: { default: 0 },
      flags: raw.flags ?? {},
      _stats: STATS
    };
  }

  const doc = {
    _id: id,
    _key: `!${def.collection}!${id}`,
    name: raw.name,
    type: raw.type ?? def.subtype,
    img: raw.img,
    system: raw.system ?? {},
    effects: [],
    folder: null,
    sort,
    ownership: { default: 0 },
    flags: raw.flags ?? {},
    _stats: STATS
  };
  if (def.type === "Actor") {
    doc.items = [];
    // Cats show Cattitude on bar 1; residents have no bars. null (not "")
    // disables a bar; "" would be cleaned back to the primaryTokenAttribute.
    doc.prototypeToken = {
      name: raw.name, actorLink: !!raw.actorLink, texture: { src: raw.token ?? raw.img },
      bar1: { attribute: doc.type === "cat" ? "cattitude" : null }, bar2: { attribute: null }
    };
  }
  return doc;
}
